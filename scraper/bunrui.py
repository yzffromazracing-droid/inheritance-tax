from shoukei import SHOUKEI_CLASSES  # noqa: E402  事業承継タブ（中小企業庁の情報を整理したもの）

TABS = {
    "shoukei": {"label": "事業承継", "classes": SHOUKEI_CLASSES},
    "sozoku": {"label": "相続税", "classes": SOZOKU_CLASSES},
    "zoyo": {"label": "贈与税", "classes": ZOYO_CLASSES},
    "zaisan": {"label": "財産評価", "classes": HYOKA_CLASSES},
}


def _match(rule, item, paths):
    kinds = rule.get("k")
    if kinds and item["kind"] not in ((kinds,) if isinstance(kinds, str) else kinds):
        return False
    if "n" in rule and re.sub(r"[－−‐]", "-", item["number"].replace("No.", "")) not in rule["n"]:
        return False
    if "t" in rule and not re.search(rule["t"], item["title"]):
        return False
    if "p" in rule and not any(re.search(rule["p"], p) for p in paths):
        return False
    return True


def classify(item) -> dict:
    """{タブ: {区分key: テーマ名}} を返す。"""
    paths = [" > ".join([item["source"]] + c) for c in [item["category"]] + item.get("altCategories", [])]
    out = {}
    for tab, spec in TABS.items():
        tags = {}
        for cls in spec["classes"]:
            for topic in cls["topics"]:
                if any(_match(r, item, paths) for r in topic.get("rules", [])):
                    tags[cls["key"]] = topic["name"]
                    break
        if tags:
            out[tab] = tags
    return out


def export() -> dict:
    """画面用の整理表（規則を除く）。"""
    return {tab: {"label": spec["label"],
                  "classes": [{"key": c["key"], "label": c["label"], "desc": c["desc"],
                               "topics": [{k: t[k] for k in ("name", "desc", "table", "tables", "note", "links") if k in t} for t in c["topics"]]}
                              for c in spec["classes"]]}
            for tab, spec in TABS.items()}
